var symb = '-';
var a = 30; var b = 15;
switch(symb)
{
    case '+':
        console.log(`The result is ${a+b}`);
        break;

    case '-':
        console.log(`The result is ${a-b}`);
        break;

    case '*':
        console.log(`The result is ${a*b}`);
        break;

    case '/':
        console.log(`The result is ${a/b}`);
        break;
}


